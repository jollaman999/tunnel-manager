var scriptBindScope = regexp.MustCompile(`(?m)^const (bindScope[A-Za-z]+) = "([^"]*)";$`)

// TestTheScreensNameTheBindScopesTheModelStores holds the words the screens
// send against the words the column takes.
//
// The two are compared rather than written out once, because a word that does
// not match is refused nowhere the operator would see it in time: the list on
// the screen still offers two entries under sentences out of the catalog, and
// what comes back is a refusal of the whole request naming a field. The check
// on the column would be the last thing to speak, and by then the screen has
// been offering a choice it could never store.
func TestTheScreensNameTheBindScopesTheModelStores(t *testing.T) {
	want := map[string]string{
		"bindScopeWildcard": models.BindScopeWildcard,
		"bindScopeLoopback": models.BindScopeLoopback,
	}

	found := map[string]string{}

	for _, said := range scriptBindScope.FindAllStringSubmatch(readStatic(t, "screens.js"), -1) {
		found[said[1]] = said[2]
	}

	if len(found) == 0 {
		t.Fatalf("screens.js names no bind scope in the shape this test reads")
	}

	for name, word := range found {
		stored, known := want[name]
		if !known {
			t.Errorf("screens.js names the bind scope %s, which the model has no word for", name)
			continue
		}

		if word != stored {
			t.Errorf("screens.js sends %s as %q, which the model stores as %q", name, word, stored)
		}
	}

	for name := range want {
		if _, ok := found[name]; !ok {
			t.Errorf("screens.js names no %s, so one of the two scopes cannot be picked", name)
		}
	}
}

// The two shapes a script writes a request body in: the object it builds, and
// the fields it sets on that object afterwards. A field is set afterwards where
// it is only sent sometimes, an empty password box being the first of those, so
// reading the object alone would miss half of what goes out.
var (
	scriptBodyLiteral = regexp.MustCompile(`(?m)^ {4}([a-z][a-z0-9_]*):`)
	scriptBodyField   = regexp.MustCompile(`(?m)^ +body\.([a-z][a-z0-9_]*) =`)
)

// TestTheFieldsTheScreensSendAreOnesTheRequestsCarry holds what the screens put
// in a request body against what the request is bound into.
//
// A name that is in one and not in the other is the quietest failure this UI
// has. Binding leaves a field it does not know about exactly where it found it,
// so the request is answered with a 200, the screen says the Host was stored,
// and the one value the operator went in to change was dropped on the way. It
// is what a field moved from one record to another leaves behind, which is how
// the bind address became a scope on the assignment: the screens went on
// sending it under the old name to a request that had stopped carrying it.
func TestTheFieldsTheScreensSendAreOnesTheRequestsCarry(t *testing.T) {
	script := readStatic(t, "screens.js")

	for _, held := range []struct {
		name string
		into any
	}{
		{"createHost", models.CreateHostRequest{}},
		{"updateHost", models.UpdateHostRequest{}},
		// The update of a service port is bound into the request the create is
		// bound into, so both of the functions that build that body are held to
		// the one struct.
		{"servicePortBody", models.CreateServicePortRequest{}},
		{"createServicePort", models.CreateServicePortRequest{}},
		// The add and the edit of a local forward are bound into one request,
		// and so is the switch of one on or off.
		{"localForwardBody", models.LocalForwardRequest{}},
		{"localForwardFlipBody", models.LocalForwardRequest{}},
	} {
		carried := jsonFields(t, held.into)
		sent := bodyFields(t, script, held.name)

		if len(sent) == 0 {
			t.Errorf("screens.js builds no request body in %s, so nothing here is checked", held.name)
			continue
		}

		t.Logf("%s sends: %s", held.name, strings.Join(sent, " "))

		for _, field := range sent {
			if !carried[field] {
				t.Errorf("screens.js sends %q from %s, which %T does not carry",
					field, held.name, held.into)
			}
		}
	}
}

// bodyFields are the names one function of a script writes into a request body.
// The object it builds is read from the first line that opens one to the line
// that closes it at the indentation a body sits on, and the fields set on it
// afterwards are read over the whole function.
func bodyFields(t *testing.T, script, name string) []string {
	t.Helper()

	at := strings.Index(script, "function "+name+"(")
	if at < 0 {
		t.Fatalf("screens.js has no function named %s", name)
	}

	body := script[at:]
	if end := strings.Index(body, "\n}\n"); end >= 0 {
		body = body[:end]
	}

	var found []string

	opens := strings.Index(body, "const body = {")
	if opens < 0 {
		opens = strings.Index(body, "  return {")
	}

	if opens >= 0 {
		literal := body[opens:]
		if closes := strings.Index(literal, "\n  };"); closes >= 0 {
			literal = literal[:closes]
		}

		for _, said := range scriptBodyLiteral.FindAllStringSubmatch(literal, -1) {
			found = append(found, said[1])
		}
	}

	for _, said := range scriptBodyField.FindAllStringSubmatch(body, -1) {
		found = append(found, said[1])
	}

	sort.Strings(found)

	return found
}

// jsonFields are the names a struct is bound from, out of the tags themselves
// rather than out of a list written beside them: a tag renamed without the list
// being touched is exactly what this is here to catch.
func jsonFields(t *testing.T, of any) map[string]bool {
	t.Helper()

	shape := reflect.TypeOf(of)
	if shape.Kind() != reflect.Struct {
		t.Fatalf("%T is not a struct", of)
	}

	names := map[string]bool{}

	for i := 0; i < shape.NumField(); i++ {
		tag := shape.Field(i).Tag.Get("json")
		if tag == "" || tag == "-" {
			continue
		}

		names[strings.Split(tag, ",")[0]] = true
	}

	return names
}

// addressLineMarker is what the line under a tunnel row that says what is known
// about the addresses of its forwarded port leaves on the element it draws. The
// tests below find that line by it rather than by the name of the function, so
// that renaming the function does not quietly stop them checking anything.
const addressLineMarker = "dataset.openReach"

// claimsNotToBeMade are what the line may not say, in the English catalog,
// which is the one every other catalog is written from.
//
// None of them is measurable from here. The reply to a tcpip-forward request
// carries a port and no address, so what the SSH server bound is never said,
// and an answer to a request is not a binding: a server set to bind every
// interface takes both address families on the first request and turns the
// second one down, for a request that named the loopback address as much as for
// one that named the wildcard. A line that reads an answer as a port that is
// open, or as traffic that will not arrive, is telling an operator something
// this program has not measured and cannot.
var claimsNotToBeMade = []string{
	"refus", "reject", "denied", "turned down",
	"alone", "only", "half of",
	"unreachable", "not reachable", "cannot be reached",
	"does not arrive", "never arrives", "nothing that dials",
	"is open on", "opened on", "not open",
}

// TestTheAddressLineClaimsNothingItCannotMeasure holds the sentences under a
// tunnel row to what was asked, what was answered and what a connection from
// here confirmed.
//
// The words are held rather than the drawing because the words are what an
// operator acts on. A sentence that says the Host turned an address down and
// that nothing reaches it over that family sends them to change a machine that
// may have the port open, and there is nothing on the screen to tell them
// otherwise.
func TestTheAddressLineClaimsNothingItCannotMeasure(t *testing.T) {
	base := readCatalog(t, baseCatalog)
	named := regexp.MustCompile(`\bt\("([^"]+)"`)

	held := map[string]bool{}

	// The keys the line itself names, which is what catches a line drawn from
	// the sentences it used to be drawn from.
	for _, use := range named.FindAllStringSubmatch(
		scriptFunctionCarrying(t, readStatic(t, "screens.js"), addressLineMarker), -1) {
		held[use[1]] = true
	}

	// And the keys of the group it is written in, which is what catches a
	// sentence added to one of the functions it is put together by.
	for key := range base {
		if strings.HasPrefix(key, "status.addresses-") {
			held[key] = true
		}
	}

	t.Logf("sentences the address line is made of: %d", len(held))

	if len(held) == 0 {
		t.Fatalf("no sentence of the address line was found, so this test checks nothing")
	}

	for key := range held {
		value := strings.ToLower(base[key])

		for _, claim := range claimsNotToBeMade {
			if strings.Contains(value, claim) {
				t.Errorf("the English catalog says %q under %q, which is not something this end "+
					"measured: an answer to a forward request is not what the server bound", claim, key)
			}
		}
	}
}

// TestTheAddressLineIsNotDrawnAsAWarning keeps the note under a row a note.
//
// Nothing in it is something to go and fix. A tunnel whose ports were asked for
// on the Host itself has no address this machine can try, which is the scope
// doing what it was picked for, and painted the way a failure is it reads as a
// tunnel with something wrong with it. The one warning about reach on this
// screen is the box drawn for a port that was tried and gave nothing back.
func TestTheAddressLineIsNotDrawnAsAWarning(t *testing.T) {
	const warningClass = "reach-advice"

	body := scriptFunctionCarrying(t, readStatic(t, "screens.js"), addressLineMarker)
	painted := regexp.MustCompile(`className = "([^"]+)"`).FindStringSubmatch(body)

	if painted == nil {
		t.Fatalf("the address line is drawn with no class of its own, so nothing here is checked")
	}

	if painted[1] == warningClass {
		t.Fatalf("the address line is drawn as %q, which is the box a port that did not answer is "+
			"warned about in", painted[1])
	}

	if style := readStatic(t, "style.css"); !strings.Contains(style, "."+painted[1]) {
		t.Fatalf("the address line is drawn as %q, which style.css has no rule for", painted[1])
	}
}

// scriptFunctionCarrying is the body of the function of a script that carries
// the string given, from the line it is declared on to the line that closes it.
// A function is found by something it does rather than by its name, so that a
// test is not answered by a rename.
func scriptFunctionCarrying(t *testing.T, script, carried string) string {
	t.Helper()

	at := strings.Index(script, carried)
	if at < 0 {
		t.Fatalf("no function of the script carries %q", carried)
	}

	opens := strings.LastIndex(script[:at], "\nfunction ")
	if opens < 0 {
		t.Fatalf("%q is not inside a function of the script", carried)
	}

	body := script[opens+1:]
	if closes := strings.Index(body, "\n}\n"); closes >= 0 {
		body = body[:closes]
	}

	return body
}
