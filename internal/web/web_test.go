// newServer returns an echo instance with nothing but the UI on it. No request
// made against it carries a cookie, so every answer it gives is an answer
// given without a session.
func newServer() *echo.Echo {
	e := echo.New()
	RegisterRoutes(e, "test-version")

	return e
}

// get runs a GET against e and hands back what was written. No cookie is ever
// attached: the UI has to be reachable by a client that has not logged in.
func get(e *echo.Echo, target string) *httptest.ResponseRecorder {
	req := httptest.NewRequest(http.MethodGet, target, nil)
	rec := httptest.NewRecorder()

	e.ServeHTTP(rec, req)

	return rec
}

// TestEmbeddedFilesArePresent lists what the binary carries. The routes below
// are only worth testing if the files they serve went into the embed in the
// first place, and a file that was renamed but not re-listed fails here rather
// than as a 404 somewhere else.
func TestEmbeddedFilesArePresent(t *testing.T) {
	var names []string

	err := fs.WalkDir(staticFS, ".", func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if !entry.IsDir() {
			names = append(names, name)
		}

		return nil
	})
	if err != nil {
		t.Fatalf("failed to walk the embedded files: %v", err)
	}

	sort.Strings(names)
	t.Logf("embedded files: %v", names)

	want := []string{
		"static/app.js", "static/index.html", "static/screens.js", "static/style.css",
		// The OpenAPI description of /api/**, generated by `make openapi` and
		// committed. It travels in the binary so that a running server can
		// hand it out, which is what the Swagger UI under /ui/api-docs/ reads
		// and what docs/reference.md sends a client to.
		"static/" + specFile,
		// The documentation page and its configuration, written here, and the
		// copy of Swagger UI they load, fetched by `make swagger-ui` and
		// committed beside the licence it is under. They are in the binary for
		// the same reason the screens are: a host that reaches nothing but
		// this server still has to be able to read its own API.
		"static/" + apiDocsDir + "/" + apiDocsIndex,
		"static/" + apiDocsDir + "/init.js",
		"static/" + apiDocsDir + "/LICENSE",
		"static/" + apiDocsDir + "/swagger-ui-bundle.js",
		"static/" + apiDocsDir + "/swagger-ui.css",
		"static/icons/apple-touch-icon.png", "static/icons/favicon-32.png",
		"static/icons/favicon.ico", "static/icons/icon-192.png", "static/icons/icon-512.png",
		"static/icons/logo.svg",
	}
	for _, code := range catalogCodes {
		want = append(want, "static/lang/"+code+".json")
	}

	sort.Strings(want)

	if strings.Join(names, " ") != strings.Join(want, " ") {
		t.Fatalf("embedded files = %v, want %v", names, want)
	}
}

// TestRootRedirectsToTheUI covers the one path that sends a client to /ui/.
// The only other path outside /ui/ is the icon, which TestTheRootIconIsTheUIIcon
// covers.
func TestRootRedirectsToTheUI(t *testing.T) {
	rec := get(newServer(), "/")

	if rec.Code != http.StatusFound {
		t.Fatalf("GET / = %d, want %d", rec.Code, http.StatusFound)
	}

	if location := rec.Header().Get(echo.HeaderLocation); location != uiPrefix {
		t.Fatalf("GET / Location = %q, want %q", location, uiPrefix)
	}
}

// TestTheRootIconIsTheUIIcon covers the one file served outside /ui/. A
// browser, a bookmark and an API client look for /favicon.ico at the root
// without reading any link, so it has to be there, and it has to be the same
// bytes as the icon the page links to rather than a second copy to keep in step.
func TestTheRootIconIsTheUIIcon(t *testing.T) {
	e := newServer()

	rec := get(e, rootIconPath)
	if rec.Code != http.StatusOK {
		t.Fatalf("GET %s = %d, want %d", rootIconPath, rec.Code, http.StatusOK)
	}

	if contentType := rec.Header().Get(echo.HeaderContentType); contentType != "image/x-icon" {
		t.Fatalf("GET %s Content-Type = %q, want %q", rootIconPath, contentType, "image/x-icon")
	}

	linked := get(e, "/ui/icons/favicon.ico")
	if linked.Code != http.StatusOK {
		t.Fatalf("GET /ui/icons/favicon.ico = %d, want %d", linked.Code, http.StatusOK)
	}

	if rec.Body.Len() == 0 || !bytes.Equal(rec.Body.Bytes(), linked.Body.Bytes()) {
		t.Fatalf("GET %s served %d bytes that are not the %d of /ui/icons/favicon.ico",
			rootIconPath, rec.Body.Len(), linked.Body.Len())
	}

	if got, want := rec.Header().Get("ETag"), linked.Header().Get("ETag"); got != want {
		t.Fatalf("GET %s ETag = %q, /ui/icons/favicon.ico carries %q", rootIconPath, got, want)
	}
}

