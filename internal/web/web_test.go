// keyShaped is a string literal in a script that reads as a catalog key. It is
// the same shape catalogKey holds a key to, anchored so that a sentence which
// happens to contain a dotted word is not taken for one.
var keyShaped = regexp.MustCompile(`^[a-z][a-z0-9]*(?:[-_][a-z0-9]+)*(?:\.[a-z][a-z0-9]*(?:[-_][a-z0-9]+)*)+` +
	`\.(?:title|label|hint|button|link|column|option|empty|notice|confirm|error|aria|text)$`)

// scriptKeys is every key the two scripts name, however they name it.
//
// It is not only the t("...") calls. A sentence that reads differently for one
// and for many is two keys picked between before either is looked up, and the
// navigation holds the key of each screen rather than its words, so neither of
// those is inside a t( and neither would be seen by a scan that looked only
// there.
func scriptKeys(t *testing.T) map[string]bool {
	t.Helper()

	literal := regexp.MustCompile(`"([^"\\\n]*)"`)
	keys := map[string]bool{}

	for _, name := range []string{"app.js", "screens.js"} {
		for _, found := range literal.FindAllStringSubmatch(readStatic(t, name), -1) {
			if keyShaped.MatchString(found[1]) {
				keys[found[1]] = true
			}
		}
	}

	return keys
}

// pluralParts is every part a count can fall in, as Intl.PluralRules names
// them. The scripts write out the keys of two of them, one and many, and
// plural in app.js puts the other four together at run time from those two.
var pluralParts = []string{"zero", "one", "two", "few", "many", "other"}

// pluralKeys is every key plural can put together from the pairs the scripts
// name: for each pair that reads P-one-S and P-many-S, the same key with each
// of the six parts written in. None of the four the scripts do not write out
// has to be in a catalog, since plural falls back to many and then to one, but
// a catalog that holds one of them is holding a key that is asked for.
func pluralKeys(keys map[string]bool) map[string]bool {
	out := map[string]bool{}

	for one := range keys {
		for at := strings.Index(one, "-one"); at >= 0; at = next(one, "-one", at) {
			head, tail := one[:at], one[at+len("-one"):]

			if !keys[head+"-many"+tail] {
				continue
			}

			for _, part := range pluralParts {
				out[head+"-"+part+tail] = true
			}
		}
	}

	return out
}

// next is the index of the occurrence of sub in s after at, or -1.
func next(s, sub string, at int) int {
	found := strings.Index(s[at+1:], sub)
	if found < 0 {
		return -1
	}

	return at + 1 + found
}

